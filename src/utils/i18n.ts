/**
 * Universal Translation Helper:
 * Accepts translation key or raw text and returns translation in target language script.
 */
export function getTranslation(lang: LanguageCode, keyOrText: string): string {
  if (!keyOrText) return '';
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

  // Direct key lookup
  if (dict[keyOrText]) {
    return dict[keyOrText];
  }

  // English fallback key
  if (TRANSLATIONS.en[keyOrText]) {
    return TRANSLATIONS.en[keyOrText];
  }

  // Direct string reverse match
  for (const [k, englishVal] of Object.entries(TRANSLATIONS.en)) {
    if (englishVal.toLowerCase() === keyOrText.trim().toLowerCase()) {
      return dict[k] || englishVal;
    }
  }

  return keyOrText;
}

